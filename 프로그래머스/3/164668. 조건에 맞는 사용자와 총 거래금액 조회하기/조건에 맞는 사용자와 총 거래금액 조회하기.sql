WITH OVER_USER AS (SELECT WRITER_ID, SUM(PRICE) AS TOTAL_PRICE
FROM USED_GOODS_BOARD
WHERE STATUS = 'DONE'
GROUP BY WRITER_ID
HAVING SUM(PRICE) >= 700000)

SELECT USER_ID, NICKNAME, TOTAL_PRICE
FROM USED_GOODS_USER AS UR
JOIN OVER_USER AS OU
ON UR.USER_ID = OU.WRITER_ID
ORDER BY TOTAL_PRICE ASC

