WITH ANIMAL_IO AS (SELECT ANIMAL_ID, ROW_NUMBER() OVER (ORDER BY DATE_DIFF DESC) AS RN, DATE_DIFF
FROM (
    SELECT O.ANIMAL_ID, DATEDIFF(O.DATETIME, I.DATETIME) AS DATE_DIFF
    FROM ANIMAL_OUTS AS O
    JOIN ANIMAL_INS AS I
    ON I.ANIMAL_ID = O.ANIMAL_ID
) AS ANIMAL_RANK)

SELECT I.ANIMAL_ID, I.NAME
FROM ANIMAL_INS AS I
JOIN ANIMAL_IO AS IO
ON IO.ANIMAL_ID = I.ANIMAL_ID
WHERE RN <= 2

